import { useEffect, useState, useRef } from "react";
import { Button } from "@/components/ui/button";
import { Spinner } from "@/components/ui/spinner";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Link, useNavigate } from "react-router";
import { useLogin } from "../hooks/use-login";
import { getAuthErrorMessage } from "../utils/get-auth-error-message";

import {
  sendSignInLinkToEmail,
  isSignInWithEmailLink,
  signInWithEmailLink,
  signOut,
} from "firebase/auth";
import { auth } from "../../../shared/auth";
import { httpError } from "../../../shared/http-client";
import { verify2FALogin } from "../../settings/api/mfa-api";
import { useCallback } from "react";

function LoginPage() {
  const navigate = useNavigate();
  const { error, isPending, login } = useLogin();
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");

  const [isLinkPending, setIsLinkPending] = useState(false);
  const [linkSent, setLinkSent] = useState(false);
  const [linkError, setLinkError] = useState("");

  const [showMfa, setShowMfa] = useState(false);
  const [mfaPin, setMfaPin] = useState("");
  const [isMfaVerifying, setIsMfaVerifying] = useState(false);
  const [mfaError, setMfaError] = useState("");

  const isSigningIn = useRef(false);

  const handlePostAuthCheck = useCallback(
    async user => {
      const tokenResult = await user.getIdTokenResult();
      if (tokenResult.claims.twoFactorEnabled) {
        setShowMfa(true);
      } else {
        navigate("/dashboard");
      }
    },
    [navigate],
  );

  useEffect(() => {
    if (isSignInWithEmailLink(auth, window.location.href)) {
      if (isSigningIn.current) return;
      isSigningIn.current = true;

      let storedEmail = window.localStorage.getItem("emailForSignIn");

      if (!storedEmail) {
        storedEmail = window.prompt("Please confirm your email address to sign in:");
      }

      if (storedEmail) {
        signInWithEmailLink(auth, storedEmail, window.location.href)
          .then(async result => {
            window.localStorage.removeItem("emailForSignIn");
            await handlePostAuthCheck(result.user);
          })
          .catch(err => {
            setLinkError(getAuthErrorMessage(err));
            isSigningIn.current = false;
          });
      } else {
        isSigningIn.current = false;
      }
    }
  }, [navigate, handlePostAuthCheck]);

  async function handleSubmit(event) {
    event.preventDefault();
    setLinkError("");

    try {
      await login({ email, password });

      if (auth.currentUser) {
        await handlePostAuthCheck(auth.currentUser);
      }
    } catch (err) {
      // Catch the 429 rate limit error thrown by your httpClient
      if (err instanceof httpError && err.status === 429) {
        setLinkError("Too many login attempts. Please wait a few minutes and try again.");
        return;
      }

      // Fallback for network issues or actual login failures
      setLinkError(getAuthErrorMessage(err) || "An error occurred during sign-in.");
    }
  }

  async function handleMfaSubmit(event) {
    event.preventDefault();
    setMfaError("");
    setIsMfaVerifying(true);

    try {
      await verify2FALogin(mfaPin);
      navigate("/dashboard");
    } catch (err) {
      console.error("MFA error:", err);
      setMfaError("Invalid 6-digit code. Please check your app and try again.");
    } finally {
      setIsMfaVerifying(false);
    }
  }

  async function handleCancelMfa() {
    await signOut(auth);
    setShowMfa(false);
    setMfaPin("");
    setMfaError("");
  }

  async function handlePasswordLess() {
    setLinkError("");
    if (!email) {
      setLinkError("Please enter your email address first.");
      return;
    }

    setIsLinkPending(true);

    const actionCodeSettings = {
      url: window.location.origin + "/login",
      handleCodeInApp: true,
    };

    try {
      await sendSignInLinkToEmail(auth, email, actionCodeSettings);
      window.localStorage.setItem("emailForSignIn", email);
      setLinkSent(true);
    } catch (err) {
      setLinkError(getAuthErrorMessage(err));
    } finally {
      setIsLinkPending(false);
    }
  }

  return (
    <main className="flex min-h-svh items-center justify-center bg-muted/30 px-4 py-8">
      <Card className="w-full max-w-md">
        {showMfa ? (
          <>
            <CardHeader>
              <CardTitle>Two-Factor Authentication</CardTitle>
              <CardDescription>
                Enter the 6-digit security code generated by your authentication app.
              </CardDescription>
            </CardHeader>
            <CardContent>
              <form className="space-y-5" onSubmit={handleMfaSubmit}>
                <div className="space-y-2">
                  <Label htmlFor="mfa-pin">Authenticator Code</Label>
                  <Input
                    id="mfa-pin"
                    placeholder="000000"
                    maxLength={6}
                    value={mfaPin}
                    onChange={e => setMfaPin(e.target.value.replace(/\D/g, ""))}
                    disabled={isMfaVerifying}
                    className="text-center font-mono text-lg tracking-widest"
                    autoFocus
                    required
                  />
                </div>

                {mfaError && (
                  <p className="text-sm text-destructive" role="alert">
                    {mfaError}
                  </p>
                )}

                <div className="flex flex-col gap-2 pt-2">
                  <Button
                    className="w-full"
                    disabled={isMfaVerifying || mfaPin.length !== 6}
                    type="submit"
                  >
                    {isMfaVerifying ? (
                      <>
                        <Spinner data-icon="inline-start" /> Verifying
                      </>
                    ) : (
                      "Verify Code"
                    )}
                  </Button>

                  <Button
                    type="button"
                    variant="outline"
                    className="w-full"
                    disabled={isMfaVerifying}
                    onClick={handleCancelMfa}
                  >
                    Cancel / Back to Sign In
                  </Button>
                </div>
              </form>

              <p className="mt-6 text-center text-sm text-muted-foreground">
                Having trouble getting your code? Contact our support.
              </p>
            </CardContent>
          </>
        ) : (
          <>
            <CardHeader>
              <CardTitle>Welcome back</CardTitle>
              <CardDescription>Sign in to continue planning your studies.</CardDescription>
            </CardHeader>
            <CardContent>
              {linkSent ? (
                <div className="space-y-4 text-center">
                  <p className="text-sm font-medium text-low-priority">
                    Password-less sign-in link sent! Check your email inbox.
                  </p>
                  <Button variant="outline" onClick={() => setLinkSent(false)}>
                    Back to login
                  </Button>
                </div>
              ) : (
                <form className="space-y-5" onSubmit={handleSubmit}>
                  <div className="space-y-2">
                    <Label htmlFor="email">Email</Label>
                    <Input
                      autoComplete="email"
                      id="email"
                      onChange={event => setEmail(event.target.value)}
                      placeholder="you@example.com"
                      required
                      type="email"
                      value={email}
                    />
                  </div>
                  <div className="space-y-2">
                    <Label htmlFor="password">Password (Optional for password-less sign-in)</Label>
                    <Input
                      autoComplete="current-password"
                      id="password"
                      onChange={event => setPassword(event.target.value)}
                      type="password"
                      value={password}
                    />
                  </div>

                  <div className="flex flex-col gap-2 pt-2">
                    <Button className="w-full" disabled={isPending || isLinkPending} type="submit">
                      {isPending ? (
                        <>
                          <Spinner data-icon="inline-start" /> Signing in...
                        </>
                      ) : (
                        "Sign in with Password"
                      )}
                    </Button>

                    <Button
                      type="button"
                      variant="secondary"
                      disabled={isPending || isLinkPending}
                      onClick={handlePasswordLess}
                    >
                      {isLinkPending ? "Sending link..." : "Send me password-less sign-in link"}
                    </Button>
                  </div>

                  <p className="text-center text-sm">
                    <Link
                      className="font-medium text-foreground underline underline-offset-4"
                      to="/forgot-password"
                    >
                      Forgot password?
                    </Link>
                  </p>
                </form>
              )}

              {(error || linkError) && (
                <p className="mt-3 text-sm text-destructive" role="alert">
                  {linkError || getAuthErrorMessage(error)}
                </p>
              )}

              <p className="mt-6 text-center text-sm text-muted-foreground">
                Don&apos;t have an account?{" "}
                <Link
                  className="font-medium text-foreground underline underline-offset-4"
                  to="/register"
                >
                  Register
                </Link>
              </p>
            </CardContent>
          </>
        )}
      </Card>
    </main>
  );
}

export { LoginPage };
